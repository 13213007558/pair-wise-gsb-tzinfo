    def test_annual_rules_periods_for_local_gap_and_ambiguity_in_far_future
      offsets = [{gmtoff: 0, isdst: false, abbrev: 'TST'}]
      rules = far_future_northern_rules

      tzif_test(offsets, [], rules: rules) do |path, format|
        tz = read_annual_rules_timezone(path)
        spring, fall = tz.transitions_up_to(Time.utc(3001, 1, 1), Time.utc(3000, 1, 1))

        gap_local = Time.at(spring.timestamp_value).utc + 1800
        assert_raises(PeriodNotFound) { tz.local_to_utc(gap_local) }

        # A repeated wall time during the fall-back transition is ambiguous.
        ambiguous_local = Time.at(fall.timestamp_value).utc + 1800
        periods = tz.periods_for_local(ambiguous_local)
        assert_equal(2, periods.length)
        assert_equal(fall.timestamp_value + 1800 - 3600, tz.local_to_utc(ambiguous_local, true).to_i)
        assert_equal(fall.timestamp_value + 1800, tz.local_to_utc(ambiguous_local, false).to_i)
      end
    end

    def test_annual_rules_last_defined_transition_coincides_with_footer
      rules = far_future_northern_rules
      spring_3000 = rules.transitions(3000).find {|t| t.offset.dst? }

      offsets = [
        {gmtoff: 0, isdst: false, abbrev: 'TST'},
        {gmtoff: 3600, isdst: true, abbrev: 'TDT'}
      ]
      transitions = [{at: spring_3000.timestamp_value, offset_index: 1}]

      tzif_test(offsets, transitions, rules: rules) do |path, format|
        timeline = @reader.read(path)
        assert_kind_of(TZInfo.const_get(:AnnualRulesTimeline), timeline)
        assert_equal(1, timeline.transitions.length)

        tz = DataSources.const_get(:AnnualRulesDataTimezoneInfo).new('Test/Coincident', timeline).create_timezone
        assert(!tz.period_for(Time.at(spring_3000.timestamp_value - 1)).dst?)
        assert(tz.period_for(Time.at(spring_3000.timestamp_value)).dst?)

        future = tz.transitions_up_to(Time.utc(3001, 1, 1), Time.utc(3000, 1, 1))
        # The coincident transition belongs to the history; the next reported
        # transition is the end of DST later in 3000.
        assert(future.first.timestamp_value > spring_3000.timestamp_value)
        assert_equal(0, future.first.offset.observed_utc_offset)
      end
    end

