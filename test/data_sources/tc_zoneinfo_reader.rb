    def test_annual_rules_rule_time_running_past_midnight
      offsets = [{gmtoff: 0, isdst: false, abbrev: 'TST'}]
      rules = far_future_northern_rules

      tzif_test(offsets, [], rules: rules) do |path, format|
        tz = read_annual_rules_timezone(path)
        transitions = tz.transitions_up_to(Time.utc(3001, 1, 1), Time.utc(3000, 1, 1))
        end_dst = transitions.find {|t| !t.offset.dst? }

        # 25:00 standard time on Sunday is 00:00 on Monday (standard time is in
        # force after the transition and TST is UTC, so the UTC wall time is
        # 00:00 on Monday).
        end_time = Time.at(end_dst.timestamp_value).utc
        assert_equal(0, end_dst.offset.observed_utc_offset)
        assert_equal(0, end_time.hour)
        assert_equal(1, end_time.wday)
      end
    end

